export function bitmapRects(rows: string[], ox = 0, oy = 0) {
  const out: { x: number; y: number }[] = [];
  rows.forEach((row, y) => [...row].forEach((c, x) => c === 'X' && out.push({ x: x + ox, y: y + oy })));
  return out;
}

export function wordmarkRects(word = 'PIXEL') {
  return [...word].flatMap((ch, i) => bitmapRects(LETTERS[ch], i * 6, 0));
}
